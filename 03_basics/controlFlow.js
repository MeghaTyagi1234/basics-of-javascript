//----------------- switch case---------------
let month1 = 4;
switch (month1) {
    case 1:
        console.log("januray")
        break;
    case 2:
        console.log("february")
        break;
    case 3:
        console.log("march")
        break;
    case 4:
        console.log("april")
        break;
    case 5:
        console.log("may")
        break;
    case 6:
        console.log("june")
        break;
    case 7:
        console.log("july")
        break;

    default:
        console.log("invalid month")
}